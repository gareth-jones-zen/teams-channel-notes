r"""Generate the C# tables the port needs from the Python that is the oracle, so they can't drift by hand.

    python tools/gen/gen_tables.py

Writes:
    src/TeamsChannelNotes/Html5Entities.g.cs                     html.entities.html5, the table html.unescape uses
    tests/TeamsChannelNotes.Tests/Generated/PythonWhitespace.g.cs  every BMP code point Python's str.isspace() and
                                                                    re's \s accept (they must agree)
Both carry the Python version they came from. Re-run after a Python upgrade and diff.
"""

from __future__ import annotations

import pathlib
import re
import sys
from html.entities import html5

ROOT = pathlib.Path(__file__).resolve().parents[2]
VERSION = sys.version.split()[0]
BACKSLASH = chr(92)


def cs(text: str) -> str:
    """A C# string literal, with everything outside printable ASCII as \\uXXXX escapes."""
    out = []
    for ch in text:
        code = ord(ch)
        if code > 0xFFFF:
            code -= 0x10000
            out.append(f"{BACKSLASH}u{0xD800 + (code >> 10):04X}{BACKSLASH}u{0xDC00 + (code & 0x3FF):04X}")
        elif 0x20 <= code < 0x7F and ch not in ('"', BACKSLASH):
            out.append(ch)
        else:
            out.append(f"{BACKSLASH}u{code:04X}")
    return '"' + "".join(out) + '"'


def entities() -> None:
    lines = [
        "// <auto-generated>",
        f"// From Python {VERSION}'s html.entities.html5 by tools/gen/gen_tables.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace TeamsChannelNotes;",
        "",
        "internal static partial class Html5Entities",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        "",
        "    // Name, then its replacement, in pairs.",
        "    private static readonly string[] Pairs =",
        "    [",
    ]
    for name in sorted(html5):
        lines.append(f"        {cs(name)}, {cs(html5[name])},")
    lines += ["    ];", "}", ""]
    path = ROOT / "src" / "TeamsChannelNotes" / "Html5Entities.g.cs"
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{path.relative_to(ROOT)}: {len(html5)} entities")


def whitespace() -> None:
    spaces = [c for c in range(0x10000) if chr(c).isspace()]
    regex = [c for c in range(0x10000) if re.fullmatch(r"\s", chr(c))]
    assert spaces == regex, "str.isspace() and re's \\s disagree"
    lines = [
        "// <auto-generated>",
        f"// From Python {VERSION}'s str.isspace() by tools/gen/gen_tables.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace TeamsChannelNotes.Tests;",
        "",
        "internal static class PythonWhitespace",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        "",
        "    public static readonly int[] CodePoints =",
        "    [",
        "        " + ", ".join(f"0x{c:04X}" for c in spaces) + ",",
        "    ];",
        "}",
        "",
    ]
    path = ROOT / "tests" / "TeamsChannelNotes.Tests" / "Generated" / "PythonWhitespace.g.cs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{path.relative_to(ROOT)}: {len(spaces)} code points")


if __name__ == "__main__":
    entities()
    whitespace()
